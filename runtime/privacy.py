"""Log only allowlisted service metadata, never request/response contents."""

import json
import logging
import time
import uuid


AUDIT_LOG = logging.getLogger("qwen.audit")
ROUTES = {
    "/health", "/v1/models", "/v1/chat/completions", "/v1/completions",
    "/v1/responses",
}
METHODS = {"GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS", "HEAD"}
EVENTS = {"request_started", "request_finished", "request_failed"}


class PrivacyFormatter(logging.Formatter):
    """Omit arbitrary messages, arguments, tracebacks and stack dumps.

    vLLM errors may include full inputs. They become location-only records.
    Only metadata generated by our middleware is kept verbatim.
    """

    def format(self, record):
        output = {
            "timestamp": round(record.created, 3),
            "level": record.levelname,
            "event": "runtime_log",
            "source": record.name,
            "location": f"{record.filename}:{record.lineno}",
        }
        event = getattr(record, "audit_event", None)
        if record.name == "qwen.audit" and event in EVENTS:
            output["event"] = event
            request_id = getattr(record, "request_id", "")
            if isinstance(request_id, str) and len(request_id) == 32:
                if all(char in "0123456789abcdef" for char in request_id):
                    output["request_id"] = request_id
            method = getattr(record, "http_method", "OTHER")
            output["method"] = method if method in METHODS else "OTHER"
            route = getattr(record, "http_route", "other")
            output["route"] = route if route in ROUTES else "other"
            status = getattr(record, "http_status", None)
            if isinstance(status, int) and 100 <= status <= 599:
                output["status"] = status
            duration = getattr(record, "duration_ms", None)
            if isinstance(duration, (int, float)) and 0 <= duration < 1e12:
                output["duration_ms"] = round(duration, 2)
        return json.dumps(output, ensure_ascii=True, allow_nan=False)


class AuditMiddleware:
    """ASGI middleware: no reads of headers, bodies, query strings or tokens."""

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return

        started = time.monotonic()
        fields = {
            "request_id": uuid.uuid4().hex,
            "http_method": scope.get("method", "OTHER"),
            "http_route": scope.get("path", "other"),
        }
        AUDIT_LOG.info("", extra={**fields, "audit_event": "request_started"})
        status = 500

        async def audit_send(message):
            nonlocal status
            if message["type"] == "http.response.start":
                status = message["status"]
            await send(message)

        failed = False
        try:
            await self.app(scope, receive, audit_send)
        except BaseException:
            failed = True
            raise
        finally:
            AUDIT_LOG.info("", extra={
                **fields,
                "audit_event": "request_failed" if failed else "request_finished",
                "http_status": status,
                "duration_ms": (time.monotonic() - started) * 1000,
            })
